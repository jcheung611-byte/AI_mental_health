/**
 * Simple End-to-End Test
 * Tests real TTS audio → Transcription pipeline
 * Verifies the full flow works with actual audio content
 */

require('dotenv').config({ path: '.env.local' });
const OpenAI = require('openai');
const fs = require('fs');
const path = require('path');

const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });
const VERCEL_BASE_URL = 'https://ai-mental-health-seven.vercel.app';

// Test cases
const tests = [
  {
    name: '3-minute recording',
    duration: 180,
    text: 'This is a three minute test of the transcription system. I am speaking continuously to generate enough audio content to test the full pipeline. The system should be able to handle this duration without any issues. We are testing the hybrid upload strategy where files under four point five megabytes use parallel upload and transcription. This test verifies that real audio generated by text to speech can be successfully transcribed back to text with high accuracy.'
  },
  {
    name: '5-minute recording',
    duration: 300,
    text: 'This is a five minute test of the transcription system. I am speaking continuously to generate enough audio content to test the full pipeline with a longer duration. The system should be able to handle this duration without any issues. We are testing the hybrid upload strategy where files under four point five megabytes use parallel upload and transcription for optimal performance. This test verifies that real audio generated by text to speech can be successfully transcribed back to text with high accuracy even at longer durations. The mental health companion app needs to support extended venting sessions where users may speak for several minutes without interruption. This test ensures that the backend can handle such use cases reliably.'
  }
];

async function generateAudio(text, filename) {
  console.log(`  🎙️  Generating audio: ${filename}`);
  
  const mp3 = await openai.audio.speech.create({
    model: 'tts-1',
    voice: 'nova',
    input: text,
    speed: 1.0
  });

  const buffer = Buffer.from(await mp3.arrayBuffer());
  const filePath = path.join(__dirname, 'test-results', filename);
  fs.writeFileSync(filePath, buffer);
  
  const sizeMB = (buffer.length / 1024 / 1024).toFixed(2);
  console.log(`  ✅ Generated: ${sizeMB} MB\n`);
  
  return filePath;
}

async function transcribeAudio(filePath) {
  console.log(`  📤 Uploading to /api/transcribe...`);
  
  const formData = new FormData();
  const audioBlob = new Blob([fs.readFileSync(filePath)], { type: 'audio/mpeg' });
  formData.append('audio', audioBlob, path.basename(filePath));

  const response = await fetch(`${VERCEL_BASE_URL}/api/transcribe`, {
    method: 'POST',
    body: formData
  });

  if (!response.ok) {
    const error = await response.json().catch(() => ({}));
    throw new Error(`Transcription failed: ${response.status} ${JSON.stringify(error)}`);
  }

  const data = await response.json();
  console.log(`  ✅ Transcription complete\n`);
  
  return data.text;
}

function calculateAccuracy(expected, actual) {
  // Simple word-level comparison
  const expectedWords = expected.toLowerCase().split(/\s+/);
  const actualWords = actual.toLowerCase().split(/\s+/);
  
  let matches = 0;
  const minLength = Math.min(expectedWords.length, actualWords.length);
  
  for (let i = 0; i < minLength; i++) {
    if (expectedWords[i] === actualWords[i]) {
      matches++;
    }
  }
  
  const accuracy = (matches / expectedWords.length * 100).toFixed(1);
  return accuracy;
}

async function runTests() {
  console.log('🧪 End-to-End Test - Real Audio Pipeline\n');
  console.log('Testing: TTS Generation → Upload → Transcription\n');
  console.log('═'.repeat(80));
  console.log('');

  const results = [];

  for (const test of tests) {
    console.log(`\n📝 TEST: ${test.name} (${test.duration}s)`);
    console.log('─'.repeat(80));
    
    try {
      // Step 1: Generate audio
      const filename = `e2e-${test.duration}s.mp3`;
      const filePath = await generateAudio(test.text, filename);
      
      // Step 2: Transcribe
      const transcribedText = await transcribeAudio(filePath);
      
      // Step 3: Calculate accuracy
      const accuracy = calculateAccuracy(test.text, transcribedText);
      
      console.log(`  📊 Results:`);
      console.log(`     Expected words: ${test.text.split(/\s+/).length}`);
      console.log(`     Transcribed words: ${transcribedText.split(/\s+/).length}`);
      console.log(`     Accuracy: ${accuracy}%`);
      
      results.push({
        test: test.name,
        duration: test.duration,
        accuracy: parseFloat(accuracy),
        status: '✅ PASSED'
      });
      
      console.log(`\n  ✅ TEST PASSED`);
      
    } catch (error) {
      console.log(`\n  ❌ TEST FAILED: ${error.message}`);
      results.push({
        test: test.name,
        duration: test.duration,
        error: error.message,
        status: '❌ FAILED'
      });
    }
  }

  // Summary
  console.log('\n\n' + '═'.repeat(80));
  console.log('📊 TEST SUMMARY\n');
  
  results.forEach(result => {
    console.log(`${result.status} ${result.test}`);
    if (result.accuracy) {
      console.log(`   Accuracy: ${result.accuracy}%`);
    }
    if (result.error) {
      console.log(`   Error: ${result.error}`);
    }
  });
  
  const passed = results.filter(r => r.status.includes('PASSED')).length;
  const total = results.length;
  
  console.log(`\n${passed}/${total} tests passed`);
  console.log('═'.repeat(80));
  
  if (passed === total) {
    console.log('\n✅ All tests passed! Pipeline is working correctly.\n');
  } else {
    console.log('\n⚠️  Some tests failed. Check errors above.\n');
    process.exit(1);
  }
}

// Run tests
runTests().catch(error => {
  console.error('\n❌ Test suite failed:', error);
  process.exit(1);
});

